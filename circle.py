import math


def area(r):
    '''
    Принимает число r.
    возвращает произведение квадрата r и числа пи из библиотеки math.

    пример вызова:
    S = area(5) // вернет 78.53981633974483
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает число r.
    возвращает удвоенное произведение r и числа пи из библиотеки math.

    пример вызова:
    P = perimeter(5) // вернет 31.41592653589793
    '''
    return 2 * math.pi * r
