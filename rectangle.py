def area(a,b):
    '''
    принимает два числа a и b.
    возвращает их произведение.

    пример вызова:
    S = area(3,4) // функция вернет 12
    '''
    return a*b

def perimeter(a,b):
    '''
    принимает два числа: a и b.
    возвращает удвоенное произведение их суммы.

    пример вызова:
    P = perimeter(5,4) // функция вернет 18
    '''
    return (a+b)*2