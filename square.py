
def area(a):
    '''
    принимает число a.
    возвращает квадрат числа a.

    прмиер вызова:
    S = area(8) // вернет 64.
    '''
    return a * a


def perimeter(a):
    '''
    принимает число a.
    возвращает произведение 4 и a.

    пример вызова:
    P = perimeter(8) // вернет 32.
    '''
    return 4 * a